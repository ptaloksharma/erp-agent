"""UI Contract Adapter — governance-wired frontend contract for user-facing agents.

Generated by the Securi wizard when ui_adapter == "yes". Three guarantees:

1. STERILE 403s: security blocks reach the UI as safe, structured payloads —
   never leaking tenant IDs, internal rule names, or stack traces.
2. EU AI ACT Art. 12/13: every gated decision carries a machine-readable
   reasoning trace (record-keeping + transparency) the UI can render.
3. HITL HOOKS: high-impact actions surface as approval prompts the UI can
   present, with signed resume tokens.
"""
from __future__ import annotations

import json
import time
import uuid


def sterile_403(rule: str, *, request_id: str | None = None) -> dict:
    """Fail-closed response safe for any UI — no internals."""
    return {
        "ok": False,
        "status": 403,
        "error": "action_blocked",
        "message": "This action was blocked by a security policy.",
        "request_id": request_id or str(uuid.uuid4()),
    }


def reasoning_trace(*, decision: str, rule: str, summary: str,
                    agent: str, tenant_scoped: bool = True) -> dict:
    """EU AI Act Art. 12 (record-keeping) + Art. 13 (transparency) payload.

    Safe for UI rendering: carries the rationale, never raw PII.
    """
    return {
        "trace_version": "eu-ai-act/1.0",
        "decision": decision,            # "allow" | "block" | "escalate"
        "rule_family": rule,             # e.g. "BOLA", "GDPR", "HITL"
        "summary": summary,              # plain-English rationale
        "agent": agent,
        "tenant_scoped": tenant_scoped,  # boolean, never the tenant id itself
        "timestamp": time.time(),
    }


def hitl_prompt(*, action: str, amount: float | None = None,
                currency: str = "EUR", token_id: str | None = None) -> dict:
    """High-impact action presented as an approval prompt for the UI."""
    return {
        "type": "hitl_approval_required",
        "action": action,
        "amount": amount,
        "currency": currency,
        "token_id": token_id or str(uuid.uuid4()),
        "message": f"Human approval required for {action}.",
        "options": ["approve", "reject"],
    }


def dumps(payload: dict) -> str:
    """JSON for the wire, UTF-8 safe."""
    return json.dumps(payload, ensure_ascii=False)


class UIContractAdapter:
    """Wrap an agent's responses for safe UI consumption."""

    def __init__(self, agent_name: str):
        self.agent_name = agent_name

    def wrap(self, result) -> dict:
        """Normalize ANY agent result (dict, str, or primitive) into the contract.

        Defect fix: guarded tool calls may return plain strings — never assume dict.
        """
        if not isinstance(result, dict):
            result = {"value": result}
        if result.get("ok") is False and result.get("status") == 403:
            return {
                **sterile_403(result.get("rule", "policy")),
                "trace": reasoning_trace(
                    decision="block",
                    rule=result.get("rule", "policy"),
                    summary=result.get("message", "blocked by policy"),
                    agent=self.agent_name),
            }
        return {"ok": True, "status": 200, "data": result,
                "trace": reasoning_trace(
                    decision="allow", rule="pass",
                    summary="action completed within policy",
                    agent=self.agent_name)}

    def hitl(self, action: str, *, amount: float | None = None,
             currency: str = "EUR") -> dict:
        return hitl_prompt(action=action, amount=amount, currency=currency)

    def dumps(self, payload: dict) -> str:
        """Instance-level convenience (the scaffolded agent calls this)."""
        return dumps(payload)
